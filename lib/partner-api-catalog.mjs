export function filterPartnerEndpoints({
  query = "",
  group = "All",
  access = "All",
  method = "All",
} = {}) {
  const terms = query.toLowerCase().trim().split(/\s+/).filter(Boolean);
  return PARTNER_API_CATALOG.filter((endpoint) => {
    if (group !== "All" && endpoint.group !== group) return false;
    if (access !== "All" && endpoint.access !== access) return false;
    if (method !== "All" && endpoint.method !== method) return false;
    const text = [
      endpoint.method,
      endpoint.path,
      endpoint.title,
      endpoint.description,
      endpoint.group,
      endpoint.access,
      ...endpoint.scopes,
      ...endpoint.inputs.map((input) => input.name),
    ]
      .join(" ")
      .toLowerCase();
    return terms.every((term) => text.includes(term));
  });
}

export function buildPartnerRequest(endpoint) {
  // Only catalog entries are accepted; this is a documentation formatter, not a request runner.
  const entry = PARTNER_API_CATALOG.find((item) => item.id === endpoint?.id);
  if (!entry) throw new Error("Unknown Partner API operation");
  const sampleId =
    entry.path.includes("/users/") || entry.path.includes("/user/")
      ? "usr_example"
      : entry.path.includes("/webhooks/")
        ? "whk_example"
        : entry.path.includes("/keys/")
          ? "key_example"
          : "ptn_example";
  let path = entry.path
    .replace(/\{id\}/g, sampleId)
    .replace(/\{campaignId\}/g, "cmp_example")
    .replace(/\{asset\}/g, "USDC");
  const requiredQuery = entry.inputs.filter(
    (input) => input.in === "query" && input.required,
  );
  if (requiredQuery.length)
    path +=
      "?" +
      requiredQuery
        .map(
          (input) =>
            encodeURIComponent(input.name) +
            "=" +
            encodeURIComponent(
              input.name === "vault" ? "vault_example" : "example",
            ),
        )
        .join("&");
  const lines = [
    `curl --request ${entry.method} "\${PARTNER_API_ORIGIN:?Set your Partner API origin}${path}"`,
  ];
  if (entry.access !== "Public") {
    const key =
      entry.access === "Administrative" ? "ADMIN_API_KEY" : "PARTNER_API_KEY";
    lines.push(
      `  --header "Authorization: Bearer \${${key}:?Set your API key}"`,
    );
  }
  lines.push('  --header "Accept: application/json"');
  if (entry.body) {
    lines.push('  --header "Content-Type: application/json"');
    // Current catalog examples contain no shell interpolation or private values.
    const body = JSON.stringify(entry.body, null, 2).replace(/'/g, "'\\''");
    lines.push(`  --data '${body}'`);
  }
  return lines.join(" \\\n");
}
